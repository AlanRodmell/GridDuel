export const ALL_FIGHTERS: LadderFighter[] = LADDER_TIERS.flatMap((t) => t.fighters);

export const FIGHTER_MAP: Record<string, LadderFighter> = Object.fromEntries(
  ALL_FIGHTERS.map((f) => [f.id, f])
);

export function getTierForFighter(fighterId: string): LadderTier | undefined {
  const fighter = FIGHTER_MAP[fighterId];
  if (!fighter) return LADDER_TIERS[0];
  return LADDER_TIERS.find((t) => t.tierNumber === fighter.tierNumber);
}

export function getFighterBiomes(fighterId: string): BiomeType[] {
  return getTierForFighter(fighterId)?.biomes ?? ['water', 'marsh'];
}

export function getFighterPoolLabel(fighter: LadderFighter): string {
  const base = `#${String(fighter.minCardNumber).padStart(2, '0')}–#${String(
    fighter.maxCardNumber
  ).padStart(2, '0')}`;
  if (fighter.tierNumber === 1 && fighter.orderInTier <= 3) {
    return base;
  }
  return `${base} + Realms #91–#120`;
}

export function isTierUnlocked(
  tierNumber: number,
  fighterWins: Record<string, number>
): boolean {
  if (tierNumber <= 1) return true;
  const prevTier = LADDER_TIERS.find((t) => t.tierNumber === tierNumber - 1);
  if (!prevTier) return false;
  const defeatedInPrev = prevTier.fighters.filter(
    (f) => (fighterWins[f.id] ?? 0) > 0
  ).length;
  return defeatedInPrev >= prevTier.requiredWinsToUnlockNext;
}

export function getTierProgress(
  tierNumber: number,
  fighterWins: Record<string, number>
): { defeated: number; total: number; required: number } {
  const tier = LADDER_TIERS.find((t) => t.tierNumber === tierNumber);
  if (!tier) return { defeated: 0, total: 0, required: 0 };
  const defeated = tier.fighters.filter((f) => (fighterWins[f.id] ?? 0) > 0).length;
  return {
    defeated,
    total: tier.fighters.length,
    required: tier.requiredWinsToUnlockNext,
  };
}
